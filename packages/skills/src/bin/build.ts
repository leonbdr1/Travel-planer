// npm run skills:build — bundle table and standalone validators for the
// Worker (and every other consumer): src/generated/{bundles.ts,validators.js,validators.d.ts}.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { productConfig } from '@reiseplaner/config';
import { compileValidators, validatorName } from '../compile';
import { loadAllBundles } from '../load';

const quiet = process.argv.includes('--quiet');
const outDir = resolve(import.meta.dirname, '../generated');

function writeIfChanged(path: string, content: string): boolean {
  if (existsSync(path) && readFileSync(path, 'utf8') === content) return false;
  writeFileSync(path, content);
  return true;
}

try {
  const bundles = loadAllBundles(productConfig.ai);
  const compiled = compileValidators(bundles);
  mkdirSync(outDir, { recursive: true });

  const dts = [
    '// Generated by npm run skills:build — do not edit.',
    "import type { CompiledValidator } from '../types';",
    ...compiled.names.map((n) => `export declare const ${n}: CompiledValidator;`),
    '',
  ].join('\n');

  const entries = bundles.map((b) => {
    const data = {
      manifest: b.manifest,
      system: b.system,
      userTemplate: b.userTemplate,
      inputSchema: b.inputSchema,
      outputSchema: b.outputSchema,
    };
    const json = JSON.stringify(data, null, 2).replace(/\n}$/, '');
    return `  ${JSON.stringify(b.manifest.id)}: {\n${json
      .slice(2)
      .split('\n')
      .map((l) => `  ${l}`)
      .join('\n')},\n    validateInput: v.${validatorName(b.manifest.id, 'input')},\n    validateOutput: v.${validatorName(b.manifest.id, 'output')},\n  },`;
  });
  const ts = [
    '// Generated by npm run skills:build from packages/skills/bundles — do not edit.',
    "import type { SkillBundle } from '../types';",
    "import * as v from './validators.js';",
    '',
    'export const bundles: Readonly<Record<string, SkillBundle>> = {',
    ...entries,
    '};',
    '',
  ].join('\n');

  const changed = [
    writeIfChanged(resolve(outDir, 'validators.js'), compiled.code),
    writeIfChanged(resolve(outDir, 'validators.d.ts'), dts),
    writeIfChanged(resolve(outDir, 'bundles.ts'), ts),
  ].some(Boolean);
  if (!quiet) {
    console.log(`${bundles.length} Bundles, ${compiled.names.length} Validatoren kompiliert${changed ? '' : ' (unverändert)'}`);
    for (const b of bundles) {
      console.log(`  ${b.manifest.id} v${b.manifest.version}  ${b.manifest.model}  Deckel ${b.manifest.costCapUsdPerCall} $`);
    }
  }
} catch (err) {
  console.error(`skills:build fehlgeschlagen: ${(err as Error).message}`);
  process.exit(1);
}
